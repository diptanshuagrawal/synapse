#!/usr/bin/env bash
# gen-denylist.sh — derive leak-denylist patterns from the config registries.
#
# The repo's config files ARE the registry of real identity. Rather than hand-
# maintain a denylist (and miss new channels/people), generate ERE patterns from:
#   config/sources.yaml         org tokens, domains, repos, channel id, MCP id
#   config/people.yaml          names, emails, handles, slack/jira ids
#   config/slack_channels.yaml  channel names + ids
# Output → .publish-denylist.generated.txt (gitignored). preflight.sh reads it
# alongside the hand-curated .publish-denylist.txt + the committed leak-patterns.
#
# Self-maintaining: add a channel/person to config → it's blocked everywhere on
# the next preflight. No chat session in the loop.
set -uo pipefail

REPO="$(git rev-parse --show-toplevel)"
WORKCTX="$REPO/work-context"
OUT="$REPO/.publish-denylist.generated.txt"
PY="$WORKCTX/.venv/bin/python"; [ -x "$PY" ] || PY=python3

CONFIG="$WORKCTX/config" OUT="$OUT" "$PY" - <<'PYEOF'
import os, re, sys
from pathlib import Path
try:
    import yaml
except Exception:
    sys.exit(0)  # no yaml → skip silently; the curated denylist still applies

cfg = Path(os.environ["CONFIG"])
out = Path(os.environ["OUT"])

def load(name):
    p = cfg / name
    if not p.exists():
        return {}
    try:
        return yaml.safe_load(p.read_text()) or {}
    except Exception:
        return {}

# Collect raw literal identifiers, tagged word|literal (literal = has @ . / : → no \b).
WORD, LIT = set(), set()
def add(v, *, literal=False):
    if not v:
        return
    s = str(v).strip()
    # Skip placeholders + too-short/ambiguous tokens.
    if len(s) < 3 or s.lower() in {"example", "owner", "none", "true", "false"}:
        return
    if re.search(r"example|placeholder|yourorg|yourcompany", s, re.I):
        return
    (LIT if literal else WORD).add(s)

# HIGH-ENTROPY IDENTIFIERS ONLY. Channel *slugs* are deliberately NOT emitted:
# real channels are often common operational words (on-call, releases, standup,
# alerts) that collide with prose — they caused the false positives. Channel-name
# leaks are caught instead by the template placeholder-lint in preflight.sh, and
# channel IDs by the structural patterns in leak-patterns.txt. Likewise we SKIP
# low-entropy tokens (github handle-prefixes, short match-tokens, the owner's own
# handle — it's in the repo name — and team nicknames), and bot/product display
# names (emitted only for entries that have an email = real humans).
src = load("sources.yaml")
def dig(d, *keys):
    for k in keys:
        d = d.get(k, {}) if isinstance(d, dict) else {}
    return d
org = src.get("org", {}); add(org.get("email_domain"), literal=True); add(org.get("owner_email"), literal=True)
add(dig(src, "atlassian", "host"), literal=True)
gh = src.get("github", {}) or {}; add(gh.get("org"))
for r in gh.get("repos", []) or []: add(r, literal=True)
add(gh.get("matterai_bot"), literal=True)
for r in gh.get("codegraph_repos", []) or []: add(r)
sl = src.get("slack", {}) or {}; add(sl.get("workspace")); add(sl.get("standup_channel")); add(sl.get("mcp_server"))
for c in sl.get("mom_channels", []) or []: add(c)

ppl = load("people.yaml").get("people", []) or []
for p in ppl if isinstance(ppl, list) else []:
    if not isinstance(p, dict):
        continue
    add(p.get("email"), literal=True)
    add(p.get("slack_handle")); add(p.get("github")); add(p.get("git_name"))
    add(p.get("slack_id")); add(p.get("jira_id"))
    nm = p.get("name")
    # Full display name only, and only for real humans (have an email). Skips
    # bot/automation entries whose `name` is a generic product string
    # ("Automation for Jira") that legitimately appears in code/prose.
    if nm and " " in str(nm) and p.get("email"):
        add(nm)

chans = load("slack_channels.yaml")
chan_iter = chans.get("channels", chans) if isinstance(chans, dict) else chans
items = chan_iter.values() if isinstance(chan_iter, dict) else (chan_iter or [])
for c in items:
    if isinstance(c, dict):
        add(c.get("id"))   # channel IDs only — slugs collide with prose

lines = []
for s in sorted(WORD):
    lines.append(r"\b" + re.escape(s) + r"\b")
for s in sorted(LIT):
    lines.append(re.escape(s))

header = (
    "# AUTO-GENERATED by bin/gen-denylist.sh from config/{sources,people,slack_channels}.yaml.\n"
    "# Gitignored. Do NOT edit by hand — re-run the generator. Hand-curated real\n"
    "# tokens go in .publish-denylist.txt instead.\n"
)
out.write_text(header + "\n".join(lines) + "\n")
print(f"gen-denylist: {len(lines)} patterns → {out}")
PYEOF
